import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'
import { StyleSheetTransformer } from '@tiny/stylesheet-compiler'
import {
  INTERNAL_SCOPE_MARKER,
  INTERNAL_SCOPE_PREFIX,
  INTERNAL_TAG_MARKER_PREFIX,
} from './shared.mjs'

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const srcRoot = path.join(packageRoot, 'src')
const componentsRoot = path.join(srcRoot, 'components')
const outputDir = path.join(srcRoot, 'generated')

const basePath = path.join(srcRoot, 'styles/index.css')
if (!fs.existsSync(basePath)) throw new Error(`Missing base stylesheet: ${basePath}`)

const tags = fs.readdirSync(componentsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()

const hostRoot = postcss.parse(fs.readFileSync(basePath, 'utf8'), { from: basePath })
const componentStyles = []

function startsWithHostTag(selector, hostTag) {
  const value = selector.trim()
  return value === hostTag || value.startsWith(`${hostTag}[`)
    || value.startsWith(`${hostTag}.`) || value.startsWith(`${hostTag}:`)
}

for (const tag of tags) {
  const stylePath = path.join(componentsRoot, tag, 'index.css')
  if (!fs.existsSync(stylePath)) {
    throw new Error(`Missing built-in component stylesheet: ${stylePath}`)
  }
  const root = postcss.parse(fs.readFileSync(stylePath, 'utf8'), { from: stylePath })
  const hostTag = `tiny-${tag}`
  const internalRoot = postcss.root()
  for (const node of [...root.nodes]) {
    if (node.type === 'rule') {
      const hostSelectors = []
      const internalSelectors = []
      for (const selector of node.selectors) {
        if (startsWithHostTag(selector, hostTag)) hostSelectors.push(selector)
        else internalSelectors.push(selector)
      }
      if (hostSelectors.length > 0) {
        const hostRule = node.clone()
        hostRule.selector = hostSelectors.join(', ')
        hostRoot.append(hostRule)
      }
      if (internalSelectors.length > 0) {
        const internalRule = node.clone()
        internalRule.selector = internalSelectors.join(', ')
        internalRoot.append(internalRule)
      }
    } else if (node.type === 'atrule' && /keyframes$/i.test(node.name)) {
      hostRoot.append(node.clone())
    } else if (node.type !== 'comment') {
      internalRoot.append(node.clone())
    }
  }

  const scope = `${INTERNAL_SCOPE_PREFIX}${tag}`
  const transformer = StyleSheetTransformer.fromCss(stylePath, internalRoot.toString(), {
    classPrefix: scope,
    tagClassPrefix: `${scope}--${INTERNAL_TAG_MARKER_PREFIX}`,
    scopeMarkerClass: INTERNAL_SCOPE_MARKER,
    rpxRatio: 750,
  })
  const css = transformer.getContent()
  if (css.trim().length > 0) {
    componentStyles.push({
      tag,
      path: `tiny-builtin-${tag}.css`,
      scope,
      content: css,
    })
  }
}

const hostCss = hostRoot.toString()
fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(
  path.join(outputDir, 'styles.ts'),
  [
    '// AUTO-GENERATED by scripts/build-styles.mjs. Do not edit.',
    '// Source: src/styles/index.css and src/components/<tag>/index.css',
    `export const BUILTIN_HOST_STYLES = ${JSON.stringify(hostCss)}`,
    `export const BUILTIN_BASE_STYLES = BUILTIN_HOST_STYLES`,
    `export const BUILTIN_COMPONENT_STYLES = ${JSON.stringify(componentStyles, null, 2)}`,
    '',
  ].join('\n'),
)
console.log(`[components] composed global host styles and ${componentStyles.length} scoped internal stylesheets`)
