import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const srcRoot = path.join(packageRoot, 'src')
const componentsRoot = path.join(srcRoot, 'components')
const outputDir = path.join(srcRoot, 'generated')

const basePath = path.join(srcRoot, 'styles/index.css')
if (!fs.existsSync(basePath)) throw new Error(`Missing base stylesheet: ${basePath}`)

const parts = [fs.readFileSync(basePath, 'utf8').trim()]
const tags = fs.readdirSync(componentsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()

for (const tag of tags) {
  const stylePath = path.join(componentsRoot, tag, 'index.css')
  if (!fs.existsSync(stylePath)) {
    throw new Error(`Missing built-in component stylesheet: ${stylePath}`)
  }
  parts.push(fs.readFileSync(stylePath, 'utf8').trim())
}

fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(
  path.join(outputDir, 'styles.ts'),
  [
    '// AUTO-GENERATED by scripts/build-styles.mjs. Do not edit.',
    '// Source: src/styles/index.css and src/components/<tag>/index.css',
    `export const BUILTIN_BASE_STYLES = ${JSON.stringify(parts.join('\n\n'))}`,
    '',
  ].join('\n'),
)
console.log(`[components] composed ${tags.length + 1} stylesheets`)
