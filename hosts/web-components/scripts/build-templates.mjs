import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { TmplGroup } = require('@tiny/template-compiler')

const packageRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const componentsRoot = path.join(packageRoot, 'src/components')
const outputDir = path.join(packageRoot, 'src/generated')

const tags = fs.readdirSync(componentsRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()

const group = TmplGroup.newDev()
for (const tag of tags) {
  const templatePath = path.join(componentsRoot, tag, 'template.wxml')
  if (!fs.existsSync(templatePath)) {
    throw new Error(`Missing built-in template: ${templatePath}`)
  }
  const warnings = group.addTmpl(tag, fs.readFileSync(templatePath, 'utf8'))
  if (warnings.length > 0) {
    const messages = warnings.map((warning) => `${warning.kind} at ${JSON.stringify(warning.start)}`)
    throw new Error(`Template warnings for ${tag}: ${messages.join(', ')}`)
  }
}

const generated = group.getTmplGenObjectGroups()
group.free()

fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(
  path.join(outputDir, 'templates.js'),
  [
    '// AUTO-GENERATED by scripts/build-templates.mjs. Do not edit.',
    `// Templates: ${tags.join(', ')}`,
    `const groups = ${generated}`,
    'export default groups',
    '',
  ].join('\n'),
)
fs.writeFileSync(
  path.join(outputDir, 'templates.d.ts'),
  [
    '// AUTO-GENERATED by scripts/build-templates.mjs. Do not edit.',
    'declare const groups: Record<string, (name: string) => unknown>',
    'export default groups',
    '',
  ].join('\n'),
)
console.log(`[components] precompiled ${tags.length} templates`)
